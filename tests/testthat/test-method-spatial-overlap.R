overlap_sample <- function() tibble::tibble(detected_val=1:4,left_cen=FALSE,left_limit=NA_real_,
 right_cen=FALSE,right_limit=NA_real_,amethod=c('A','A','B','B'),x=c(0,10,10,20),y=0)

test_that('method overlap uses a common grid and counts shared and union cells', {
 x <- overlap_sample(); saved <- x
 result <- method_spatial_overlap(x,10,'x','y',n_offsets=1)
 expect_named(result,c('support','methods','pairs'))
 expect_equal(result$support$n_input,4)
 expect_equal(result$support$n_spatial,4)
 expect_equal(result$methods$n_coordinate_pairs,c(2,2))
 expect_equal(result$methods$occupied_cells_mean,c(2,2))
 expect_equal(result$pairs$method_a,'A')
 expect_equal(result$pairs$method_b,'B')
 expect_equal(result$pairs$shared_cells_mean,1)
 expect_equal(result$pairs$union_cells_mean,3)
 expect_equal(result$pairs$jaccard_mean,1/3)
 expect_equal(result$pairs$fraction_origins_with_overlap,1)
 expect_equal(x,saved)
 disjoint <- x; disjoint$x <- c(0,1,100,101)
 comparison <- method_spatial_overlap(disjoint,c(1000,10,10),'x','y')
 expect_equal(comparison$pairs$cell_size,c(10,1000))
 expect_equal(comparison$pairs$jaccard_mean,c(0,1))
 expect_equal(comparison$pairs$shared_cells_mean,c(0,1))
 expect_true(all(comparison$pairs$n_origins_evaluated==4))
})

test_that('unknown methods and unavailable coordinates remain explicit rather than zero overlap', {
 x <- overlap_sample();x$x[3:4] <- NA_real_
 x <- dplyr::bind_rows(x,tibble::tibble(detected_val=c(5,6,0),left_cen=FALSE,left_limit=NA_real_,
  right_cen=FALSE,right_limit=NA_real_,amethod=c(NA,'UNKNOWN','C'),x=c(30,40,50),y=0))
 result <- method_spatial_overlap(x,10,'x','y')
 expect_equal(result$support$n_input,7)
 expect_equal(result$support$n_usable_chemistry,6)
 expect_equal(result$support$n_excluded_chemistry,1)
 expect_equal(result$support$n_unlocated_usable,2)
 expect_equal(result$support$n_spatial,4)
 expect_equal(result$support$n_unresolved_spatial,2)
 expect_equal(result$support$n_named_codes_input,3)
 expect_equal(result$support$n_named_codes_spatial,1)
 expect_equal(nrow(result$pairs),3)
 expect_true(all(result$pairs$n_origins_evaluated==0))
 expect_true(all(is.na(result$pairs$jaccard_mean)))
 expect_true(all(is.na(result$pairs$shared_cells_mean)))
 expect_true(all(result$pairs$overlap_status=='unavailable_spatial_data'))
 unavailable <- result$methods$method_code%in%c('B','C')
 expect_true(all(is.na(result$methods$occupied_cells_mean[unavailable])))
 expect_true(anyNA(result$methods$method_code))
 expect_true('UNKNOWN'%in%result$methods$method_code)
 expect_false(anyNA(result$pairs$method_a))
 expect_false(any(result$pairs$method_a=='UNKNOWN'|result$pairs$method_b=='UNKNOWN'))
})

test_that('empty and unlocated domains keep missing anchors and typed empty tables', {
 x <- overlap_sample()
 empty <- method_spatial_overlap(x[FALSE,],c(10,20),'x','y')
 expect_equal(empty$support$n_input,0)
 expect_true(is.na(empty$support$grid_anchor_x))
 expect_true(is.na(empty$support$grid_anchor_y))
 expect_equal(nrow(empty$methods),0)
 expect_equal(nrow(empty$pairs),0)
 expect_type(empty$methods$method_code,'character')
 expect_type(empty$pairs$overlap_status,'character')
 x$x <- NA_real_
 unlocated <- method_spatial_overlap(x,10,'x','y')
 expect_equal(unlocated$support$n_unlocated_usable,4)
 expect_true(all(is.na(unlocated$methods$occupied_cells_mean)))
 expect_true(all(is.na(unlocated$pairs$jaccard_mean)))
 expect_true(is.na(unlocated$support$grid_anchor_x))
 x$detected_val <- 0
 invalid <- method_spatial_overlap(x,10,'x','y')
 expect_equal(invalid$support$n_excluded_chemistry,4)
 expect_equal(invalid$support$n_unlocated_usable,0)
})

test_that('normalization, missing method columns and custom code fields preserve method information', {
 x <- overlap_sample();x$amethod <- factor(c(' ES_SQ ','es_sq',' aes_hf ','AES_HF'))
 names(x)[names(x)=='amethod'] <- 'assay'
 result <- method_spatial_overlap(x,10,'x','y',method_col='assay')
 expect_equal(result$methods$method_code,c('AES_HF','ES_SQ'))
 expect_equal(result$methods$n_input,c(2,2))
 expect_equal(result$methods$method_information,c('method_not_reviewed','review_semiquantitative'))
 expect_match(result$methods$method_review_source[2],'pubs.usgs.gov',fixed=TRUE)
 expect_true(is.na(result$methods$method_review_source[1]))
 absent <- method_spatial_overlap(x,10,'x','y')
 expect_equal(nrow(absent$methods),1)
 expect_true(is.na(absent$methods$method_code))
 expect_equal(absent$methods$method_information,'method_not_supplied')
 expect_equal(nrow(absent$pairs),0)
 expect_equal(absent$support$n_unresolved_spatial,4)
})

test_that('input order, coordinate translation and record replication preserve cell overlap', {
 x <- overlap_sample()
 x$x <- c(0,7,4,11);x$y <- c(0,9,3,12)
 ref <- method_spatial_overlap(x,c(5,10),'x','y',n_offsets=3)
 reordered <- method_spatial_overlap(x[4:1,],c(5,10),'x','y',n_offsets=3)
 expect_equal(reordered,ref)
 x$x <- x$x+100000;x$y <- x$y-200000
 translated <- method_spatial_overlap(x,c(5,10),'x','y',n_offsets=3)
 expect_equal(translated$methods,ref$methods)
 expect_equal(translated$pairs,ref$pairs)
 expect_equal(translated$support$grid_anchor_x-ref$support$grid_anchor_x,100000)
 repeated <- method_spatial_overlap(x[rep(1:4,each=5),],c(5,10),'x','y',n_offsets=3)
 expect_equal(repeated$pairs$jaccard_mean,ref$pairs$jaccard_mean)
 expect_equal(repeated$pairs$shared_cells_mean,ref$pairs$shared_cells_mean)
 expect_equal(repeated$methods$n_coordinate_pairs,ref$methods$n_coordinate_pairs)
 expect_equal(repeated$methods$n_input,5*ref$methods$n_input)
})

test_that('censoring eligibility and common anchors use only chemistry with finite coordinates', {
 x <- overlap_sample()
 x$left_cen[1] <- TRUE # Invalid limit: do not fall back to the detected value.
 x$right_cen[4] <- TRUE;x$right_limit[4] <- 20
 result <- method_spatial_overlap(x,10,'x','y')
 expect_equal(result$support$n_usable_chemistry,3)
 expect_equal(result$support$grid_anchor_x,10)
 expect_equal(result$methods$n_spatial,c(1,2))
 expect_equal(result$methods$n_excluded_chemistry,c(1,0))
 x$right_cen[1] <- TRUE
 expect_error(method_spatial_overlap(x,10,'x','y'),'both left- and right-censored')
})

test_that('overlap audit validates geometry, cell sizes, methods and element scope', {
 x <- overlap_sample()
 for (bad in list(0,-1,NA_real_,Inf,numeric(),'10'))
  expect_error(method_spatial_overlap(x,bad,'x','y'),'cell_sizes')
 for (bad in list(0,1.5,NA_real_,Inf,numeric(),1e6))
  expect_error(method_spatial_overlap(x,10,'x','y',n_offsets=bad),'n_offsets')
 expect_error(method_spatial_overlap(x,10,'x','x'),'distinct numeric projected')
 expect_error(method_spatial_overlap(x,10,'missing','y'),'distinct numeric projected')
 expect_error(method_spatial_overlap(x,10,c('x','y'),'y'),'distinct numeric projected')
 bad <- x;bad$x <- as.character(bad$x)
 expect_error(method_spatial_overlap(bad,10,'x','y'),'distinct numeric projected')
 expect_error(method_spatial_overlap(x,10,'x','y',method_col=NA_character_),'method_col')
 expect_error(method_spatial_overlap(x,10,'x','y',method_col='x'),'differ from the method')
 x$species <- c('Ag','Ag','Pb','Pb')
 expect_error(method_spatial_overlap(x,10,'x','y'),'Select one element')
 x$species <- 'Ag';x$x <- c(-1e308,1e308,0,1)
 expect_error(method_spatial_overlap(x,1,'x','y'),'too small relative')
})

test_that('large representable grid indices do not merge distinct cells', {
 x <- overlap_sample();x$x <- x$y <- c(0,1,4e15,4e15+1)
 result <- method_spatial_overlap(x,1,'x','y',n_offsets=1)
 expect_equal(result$methods$occupied_cells_mean,c(2,2))
 expect_equal(result$pairs$shared_cells_mean,0)
 expect_equal(result$pairs$union_cells_mean,4)
 expect_equal(result$pairs$jaccard_mean,0)
})
