run_analysis_example <- function(script,args) {
  file <- system.file("examples",script,package="geoCensor")
  if(!nzchar(file))file <- testthat::test_path("..","..","inst","examples",script)
  log <- tempfile(fileext=".log")
  previous <- Sys.getenv("R_LIBS",unset=NA_character_)
  on.exit(if(is.na(previous))Sys.unsetenv("R_LIBS") else Sys.setenv(R_LIBS=previous),add=TRUE)
  Sys.setenv(R_LIBS=paste(.libPaths(),collapse=.Platform$path.sep))
  executable <- file.path(R.home("bin"),if(.Platform$OS.type=="windows")"Rscript.exe" else "Rscript")
  status <- suppressWarnings(system2(executable,
    args=shQuote(c(file,args)),stdout=log,stderr=log))
  list(status=status,log=readLines(log,warn=FALSE))
}

test_that("installed export command writes all or selected species and protects outputs", {
  root <- tempfile("geocensor_export_command_");dir.create(root)
  path <- file.path(root,"chemistry.csv")
  writeLines(c("lab_id,species,qvalue,unit","001,Ag,4.11110,ppm","001,Pb,2,ppm"),path)
  dest <- file.path(root,"all")
  run <- run_analysis_example("export_chemistry.R",c(path,dest,"--chunk-size=1"))
  expect_equal(run$status,0L,info=paste(run$log,collapse="\n"))
  if(run$status!=0L)return(invisible(NULL))
  expect_identical(read_usgs_chemistry(file.path(dest,"chemistry.csv")),read_usgs_chemistry(path))
  expect_equal(readRDS(file.path(dest,"export_info.rds"))$n_selected,2)
  selected <- file.path(root,"selected")
  run <- run_analysis_example("export_chemistry.R",c(path,selected,"--elements=Ag"))
  expect_equal(run$status,0L,info=paste(run$log,collapse="\n"))
  if(run$status!=0L)return(invisible(NULL))
  expect_identical(read_usgs_chemistry(file.path(selected,"chemistry.csv"))$qvalue,"4.11110")
  before <- tools::md5sum(list.files(dest,full.names=TRUE))
  run <- run_analysis_example("export_chemistry.R",c(path,dest))
  expect_true(run$status!=0L)
  expect_identical(tools::md5sum(list.files(dest,full.names=TRUE)),before)
  bad <- file.path(root,"bad")
  run <- run_analysis_example("export_chemistry.R",c(path,bad,"--elements=Ag,"))
  expect_true(run$status!=0L);expect_false(file.exists(bad))
  cat("002,Pb,3,ppm,extra\n",file=path,append=TRUE)
  run <- run_analysis_example("export_chemistry.R",c(path,bad,"--elements=Ag","--chunk-size=1"))
  expect_true(run$status!=0L);expect_false(file.exists(bad))
  expect_false(dir.exists(file.path(root,".bad.geoCensor-lock")))
})

test_that("installed all-element command preserves text groups and unlocated rows", {
  root <- tempfile("geocensor_command_");dir.create(root)
  chem <- file.path(root,"chemistry.csv");metadata <- file.path(root,"metadata.csv")
  readr::write_csv(tibble::tibble(lab_id=sprintf("%03d",1:6),species="Ag",unit="ppm",
    qvalue=c("1","2","3","4.11110","5","6"),qualifier=c("","L","G","","",""),
    rec_id=c("9007199254740993",as.character(2:6)),amethod="MS_HF"),chem)
  readr::write_csv(tibble::tibble(lab_id=sprintf("%03d",1:6),state="001",
    x=c("0","Inf","NA","20","30","40"),y=as.character(1:6)),metadata)
  dest <- file.path(root,"result")
  run <- run_analysis_example("analyze_all_elements.R",c(chem,dest,metadata,"x","y","100","state","--audit-source-precision"))
  expect_equal(run$status,0L,info=paste(run$log,collapse="\n"))
  if(run$status!=0L)return(invisible(NULL))
  x <- readRDS(file.path(dest,"analysis.rds"))
  expect_identical(x$estimates$state,"001")
  expect_equal(x$estimates$n_total,6)
  expect_equal(x$estimates$n_left,1)
  expect_equal(x$estimates$n_right,1)
  expect_equal(x$declustering$n_excluded,2)
  expect_identical(x$source_precision$rec_id[1],"9007199254740993")
  expect_identical(x$source_precision$qvalue[4],"4.11110")
  expect_true(all(is.na(x$declustering$ci_low)))
  # Invalid numeric text must fail before creating a new result directory.
  d <- readr::read_csv(metadata,col_types=readr::cols(.default=readr::col_character()),show_col_types=FALSE)
  d$x[5] <- "40 N";readr::write_csv(d,metadata)
  invalid <- file.path(root,"invalid")
  run <- run_analysis_example("analyze_all_elements.R",c(chem,invalid,metadata,"x","y","100","state"))
  expect_true(run$status!=0L)
  expect_match(paste(run$log,collapse="\n"),"coordinate column.*input rows: 5")
  expect_false(dir.exists(invalid))
})

test_that("single-element chunk option preserves results and rejects late bad input", {
  root <- tempfile("geocensor_select_command_"); dir.create(root)
  path <- file.path(root,"chemistry.csv")
  x <- tibble::tibble(lab_id=sprintf("%03d",1:8),
    species=rep(c("Ag","Pb"),4),unit="ppm",qvalue=as.character(1:8),
    qualifier="",amethod="MS_HF",source_record_number="000007")
  x$qvalue[3] <- "4.11110"; x$qualifier[5] <- "G"
  readr::write_csv(x,path)
  ordinary <- file.path(root,"ordinary"); selected <- file.path(root,"selected")
  a <- run_analysis_example("analyze_element_dataset.R",c(path,"Ag",ordinary,"--audit-source-precision"))
  b <- run_analysis_example("analyze_element_dataset.R",c(path,"Ag",selected,"--audit-source-precision","--chunk-size=3"))
  expect_equal(a$status,0L,info=paste(a$log,collapse="\n"))
  expect_equal(b$status,0L,info=paste(b$log,collapse="\n"))
  if(a$status!=0L || b$status!=0L)return(invisible(NULL))
  expect_identical(readRDS(file.path(selected,"analysis.rds")),readRDS(file.path(ordinary,"analysis.rds")))
  index <- readr::read_csv(file.path(selected,"input_record_index.csv"),show_col_types=FALSE)
  expect_identical(index$source_data_record,c(1,3,5,7))
  expect_false(file.exists(file.path(ordinary,"input_record_index.csv")))
  before <- tools::md5sum(list.files(selected,full.names=TRUE))
  rerun <- run_analysis_example("analyze_element_dataset.R",c(path,"Ag",selected,"--chunk-size=3"))
  expect_true(rerun$status!=0L)
  expect_match(paste(rerun$log,collapse="\n"),"not empty")
  expect_identical(tools::md5sum(list.files(selected,full.names=TRUE)),before)
  cat("009,Pb,2,ppm,,MS_HF,000007,extra\n",file=path,append=TRUE)
  invalid <- file.path(root,"invalid")
  bad <- run_analysis_example("analyze_element_dataset.R",c(path,"Ag",invalid,"--chunk-size=3"))
  expect_true(bad$status!=0L)
  expect_match(paste(bad$log,collapse="\n"),"Chemistry CSV parsing")
  expect_false(dir.exists(invalid))
  option <- run_analysis_example("analyze_element_dataset.R",c(path,"Ag",invalid,"--chunk-size=0"))
  expect_true(option$status!=0L)
  expect_match(paste(option$log,collapse="\n"),"positive integer")
})
